library(tidyr)
library(ggplot2)
students<-data.frame(
  student=c("reethu","deepu","krishna","priya","raja"),
  math=c(99,98,97,96,95),
  science=c(100,68,79,89,90),
  english=c(56,78,90,78,99),
  hours=c(1,2,3,4,5)
)
head(students)
long_df<-pivot_longer(
  students,
  cols=c(math,science,english),
  names_to="subject",
  values_to="score"
)
ggplot(long_df,aes(x=subject,y=score,fill=subject))+geom_boxplot(alpha=.7,outlier.color="red")+
  geom_jitter(width=0.2,alpha=0.5)+
  scale_fill_brewer(palette="set2")+
  labs(
    title="score distribution by subject",
    x="subject",
    y="score"
  )+
  theme_light()+
  theme(legend.position="none")
